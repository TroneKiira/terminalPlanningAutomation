using Grasshopper.Kernel;
using Rhino.Geometry;
using System;
using System.Collections.Generic;

using AirportPlanning.Core.Queueing;
using AirportPlanning.Core.Models;

namespace AirportPlanning.Components
{
    public class QueueStatistics : GH_Component
    {
        /// <summary>
        /// Initializes a new instance of the QueueMetricsComponent class.
        /// </summary>
        public QueueStatistics()
          : base("Queue Statistics", "QS",
        "Extracts performance statistics from queue simulation results.",
        "Airport Planning", "Analysis")
        {

        }

        /// <summary>
        /// Registers all the input parameters for this component.
        /// </summary>
        protected override void RegisterInputParams(GH_Component.GH_InputParamManager pManager)
        {
            pManager.AddGenericParameter(
       "Queue Results",
       "QR",
       "Queue simulation results generated by a passenger processing facility.",
       GH_ParamAccess.item);
        }

        /// <summary>
        /// Registers all the output parameters for this component.
        /// </summary>
        protected override void RegisterOutputParams(GH_Component.GH_OutputParamManager pManager)
        {
            pManager.AddNumberParameter(
               "Average Wait",
               "AW",
               "Average passenger waiting time.",
               GH_ParamAccess.item);

            pManager.AddNumberParameter(
                "Maximum Wait",
                "MW",
                "Maximum passenger waiting time.",
                GH_ParamAccess.item);

            pManager.AddNumberParameter(
                "95th Percentile Wait",
                "W95",
                "95th percentile passenger waiting time.",
                GH_ParamAccess.item);

            pManager.AddIntegerParameter(
                "Peak Queue Length",
                "PQ",
                "Maximum observed queue length.",
                GH_ParamAccess.item);

            pManager.AddNumberParameter(
                "Resource Utilization",
                "RU",
                "Utilization of each processing resource.",
                GH_ParamAccess.list);
        }

        /// <summary>
        /// This is the method that actually does the work.
        /// </summary>
        /// <param name="DA">The DA object is used to retrieve from inputs and store in outputs.</param>
        protected override void SolveInstance(IGH_DataAccess DA)
        {
            QueueResults queueResults =
            null;

            if (!DA.GetData(0, ref queueResults))
                return;

            DA.SetData(
                0,
                queueResults.AverageWait);

            DA.SetData(
                1,
                queueResults.MaxWait);

            DA.SetData(
                2,
                queueResults.Wait95);

            DA.SetData(
                3,
                queueResults.PeakQueueLength);

            DA.SetDataList(
                4,
                queueResults.CounterUtilization);
        }

        /// <summary>
        /// Provides an Icon for the component.
        /// </summary>
        protected override System.Drawing.Bitmap Icon
        {
            get
            {
                //You can add image files to your project resources and access them like this:
                // return Resources.IconForThisComponent;
                return null;
            }
        }

        /// <summary>
        /// Gets the unique ID for this component. Do not change this ID after release.
        /// </summary>
        public override Guid ComponentGuid
        {
            get { return new Guid("00B92F9E-BF83-444D-9C41-292D02512594"); }
        }
    }
}